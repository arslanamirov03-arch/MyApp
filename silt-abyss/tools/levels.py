# build + validate
# ===================================================================

CREATURE_CHARS = set("1234567")
SWITCH_CHARS = set("pqnmlLy")
GATE_CHARS = set("gGH")


def build(lv):
    """Apply bars/holes, pad, wrap in rock, and split into terrain + wire."""
    rows = [r for r in lv["art"].split("\n") if r != ""]
    w = max(len(r) for r in rows)
    grid = [list(r.ljust(w, ".")) for r in rows]

    clobbered = []
    for col, ch in lv["bars"]:
        for r in range(len(grid)):
            was = grid[r][col]
            if was == "#":
                continue            # rock already blocks; leave it alone
            if was != ".":
                clobbered.append((col, r, was))
            grid[r][col] = ch
    lv["_clobbered"] = clobbered
    for col, row in lv["holes"]:
        grid[row][col] = "."

    terrain, wire = [], []
    for r in range(len(grid)):
        trow, wrow = [], []
        for c in range(w):
            ch = grid[r][c]
            if ch in MECH:
                base, chan = MECH[ch]
                trow.append(base)
                wrow.append(str(chan))
            else:
                trow.append(ch)
                wrow.append(" ")
        terrain.append("".join(trow))
        wire.append("".join(wrow))

    border = "#" * (w + 4)
    terrain = [border] + ["##" + r + "##" for r in terrain] + [border]
    blank = " " * (w + 4)
    wire = [blank] + ["  " + r + "  " for r in wire] + [blank]
    has_wire = any(ch.isdigit() for r in wire for ch in r)
    return terrain, (wire if has_wire else None)


def channel_at(wire, c, r):
    if not wire or r >= len(wire) or c >= len(wire[r]):
        return 0
    ch = wire[r][c]
    return int(ch) if ch.isdigit() else 0


def passable(ch, creatures, open_ch, chan):
    if ch == "#":
        return False
    if ch == "k":
        return BITER in creatures
    if ch == "r":
        return RAMMER in creatures
    if ch == "g":
        return chan in open_ch
    return True


def flood(terrain, wire, start, creatures, open_ch):
    h, w = len(terrain), len(terrain[0])
    seen = {start}
    q = deque([start])
    while q:
        c, r = q.popleft()
        for dc, dr in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nc, nr = c + dc, r + dr
            if not (0 <= nc < w and 0 <= nr < h) or (nc, nr) in seen:
                continue
            if passable(terrain[nr][nc], creatures, open_ch, channel_at(wire, nc, nr)):
                seen.add((nc, nr))
                q.append((nc, nr))
    return seen


def heavy_reach(terrain, wire, starts, creatures, open_ch):
    """Where a HEAVY can get: walk sideways, fall, never climb."""
    h, w = len(terrain), len(terrain[0])

    def openc(c, r):
        if not (0 <= c < w and 0 <= r < h):
            return False
        return passable(terrain[r][c], creatures, open_ch, channel_at(wire, c, r))

    def settle(c, r):
        while openc(c, r + 1):
            r += 1
        return c, r

    seen, q = set(), deque()
    for s in starts:
        p = settle(*s)
        seen.add(p)
        q.append(p)
    while q:
        c, r = q.popleft()
        for dc in (1, -1):
            if openc(c + dc, r):
                p = settle(c + dc, r)
                if p not in seen:
                    seen.add(p)
                    q.append(p)
    return seen


def positions_of(terrain):
    pos = {}
    for r, row in enumerate(terrain):
        for c, ch in enumerate(row):
            pos.setdefault(ch, []).append((c, r))
    return pos


def solve(terrain, wire, pos, banned=()):
    """Fixpoint: which creatures can be reached, which channels open, and is the
    exit reachable? Returns (reachable_set, creatures, open_channels)."""
    start = pos["S"][0]
    creatures, open_ch = set(), set()

    for _ in range(24):
        reach = flood(terrain, wire, start, creatures, open_ch)
        grew = False

        for ch in CREATURE_CHARS:
            t = int(ch)
            if t in banned:
                continue
            for p in pos.get(ch, []):
                if p in reach and t not in creatures:
                    creatures.add(t)
                    grew = True

        heavy_cells = set()
        if HEAVY in creatures:
            starts = [p for p in pos.get("5", []) if p in reach]
            if starts:
                heavy_cells = heavy_reach(terrain, wire, starts, creatures, open_ch)

        by_channel = {}
        for kind in "pnl":
            for p in pos.get(kind, []):
                chan = channel_at(wire, p[0], p[1])
                ok = False
                if p in reach:
                    if kind == "p":
                        ok = HEAVY in creatures and p in heavy_cells
                    elif kind == "n":
                        ok = SPARK in creatures
                    else:
                        ok = BITER in creatures or RAMMER in creatures
                by_channel.setdefault(chan, []).append(ok)

        for chan, oks in by_channel.items():
            if all(oks) and chan not in open_ch:
                open_ch.add(chan)
                grew = True

        if not grew:
            break

    return flood(terrain, wire, start, creatures, open_ch), creatures, open_ch


def analyse(lv):
    terrain, wire = build(lv)
    h, w = len(terrain), len(terrain[0])
    errs, warns = [], []

    pos = positions_of(terrain)
    counts = {ch: len(v) for ch, v in pos.items()}

    for r in range(h):
        if len(terrain[r]) != w:
            errs.append(f"row {r} width {len(terrain[r])} != {w}")

    if counts.get("S", 0) != 1:
        errs.append(f"need exactly 1 'S', found {counts.get('S', 0)}")
    if counts.get("X", 0) != 1:
        errs.append(f"need exactly 1 'X', found {counts.get('X', 0)}")
    if lv["boss"] and counts.get("B", 0) != 1:
        errs.append("boss level needs exactly one 'B'")
    if not lv["boss"] and counts.get("B", 0):
        errs.append("'B' present but boss id is 0")
    for (c, r, was) in lv.get("_clobbered", []):
        errs.append(f"bar at column {c} overwrote '{was}' on row {r}")
    if counts.get("W", 0) > len(lv["whispers"]):
        warns.append(f"{counts.get('W', 0)} whisper markers, {len(lv['whispers'])} lines")
    if not lv["hints"]:
        warns.append("no hints authored")

    # Gate/switch wiring.
    gate_ch = {channel_at(wire, c, r) for (c, r) in pos.get("g", [])}
    sw_ch = set()
    for kind in "pnl":
        for (c, r) in pos.get(kind, []):
            sw_ch.add(channel_at(wire, c, r))
    for gc in sorted(gate_ch):
        if gc not in sw_ch:
            errs.append(f"gate channel {gc} has no switch")
    for sc in sorted(sw_ch):
        if sc not in gate_ch:
            warns.append(f"switch channel {sc} drives no gate")

    # Required creature per mechanism.
    if counts.get("k") and not counts.get("1"):
        errs.append("kelp but no BITER")
    if counts.get("r") and not counts.get("2"):
        errs.append("brittle rock but no RAMMER")
    if counts.get("p") and not counts.get("5"):
        errs.append("plate but no HEAVY")
    if counts.get("n") and not counts.get("4"):
        errs.append("node but no SPARK")
    if counts.get("l") and not (counts.get("1") or counts.get("2")):
        errs.append("lever but no BITER or RAMMER")

    if errs:
        return errs, warns

    exit_pos = pos["X"][0]
    reach, creatures, open_ch = solve(terrain, wire, pos)
    if exit_pos not in reach:
        errs.append("EXIT UNREACHABLE - level cannot be finished")
        return errs, warns

    for ch in CREATURE_CHARS:
        if ch in counts and int(ch) not in creatures:
            warns.append(f"{CREATURE_NAMES[int(ch)]} is present but never reachable")

    # Necessity: taking away a creature the level provides should break it.
    if not lv["soft"]:
        for t in sorted(creatures - lv["optional"]):
            reach2, _, _ = solve(terrain, wire, pos, banned={t})
            if exit_pos in reach2:
                warns.append(f"{CREATURE_NAMES[t]} is not required - "
                             "is there a way around its barrier?")

    return errs, warns


