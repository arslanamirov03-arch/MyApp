LEVELS = []


def level(title, chapter, art, bars=(), holes=(), hints=(), whispers=(), boss=0,
          dark=0.0, depth=0.0, soft=False, optional=()):
    """soft=True: the challenge is dodging or timing, not topology, so skip the
    "this creature must be required" check entirely.
    optional=[...]: creatures that are deliberately a convenience rather than a
    key - a glower carried for visibility, a rammer offered as an escape."""
    LEVELS.append(dict(title=title, chapter=chapter, art=art, bars=list(bars),
                       holes=list(holes), hints=list(hints),
                       whispers=list(whispers), boss=boss, dark=dark,
                       depth=depth, soft=soft, optional=set(optional)))


