def jstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit():
    o = []
    a = o.append
    a("package com.abyss.silt.level;\n")
    a("/**")
    a(" * Generated by tools/levels.py - do not edit by hand.")
    a(" * Every level below has passed that script's structural, solvability and")
    a(" * necessity checks, including a reachability proof for the exit.")
    a(" */")
    a("public final class Levels {\n")
    a("    private Levels() {}\n")
    a("    private static final String[] CHAPTER_TITLES = {")
    for t in CHAPTERS:
        a(f"        {jstr(t)},")
    a("    };\n")
    a("    public static String chapterTitle(int chapter) {")
    a("        int i = chapter - 1;")
    a("        return (i >= 0 && i < CHAPTER_TITLES.length) ? CHAPTER_TITLES[i] : \"\";")
    a("    }\n")
    a("    private static final LevelDef[] ALL = {")
    for i, lv in enumerate(LEVELS):
        terrain, wire = build(lv)
        a("        new LevelDef(%d, %d, %s," % (i, lv["chapter"], jstr(lv["title"])))
        a("            new String[]{")
        for r in terrain:
            a(f"                {jstr(r)},")
        a("            },")
        if wire:
            a("            new String[]{")
            for r in wire:
                a(f"                {jstr(r)},")
            a("            },")
        else:
            a("            null,")
        a("            new String[]{")
        for hnt in lv["hints"]:
            a(f"                {jstr(hnt)},")
        a("            },")
        a("            new String[]{")
        for wh in lv["whispers"]:
            a(f"                {jstr(wh)},")
        a("            },")
        a("            %d).lit(%.2ff, %.2ff)," % (lv["boss"], lv["dark"], lv["depth"]))
    a("    };\n")
    a("    public static int count() {")
    a("        return ALL.length;")
    a("    }\n")
    a("    public static LevelDef get(int i) {")
    a("        if (i < 0) i = 0;")
    a("        if (i >= ALL.length) i = ALL.length - 1;")
    a("        return ALL[i];")
    a("    }")
    a("}")
    return "\n".join(o) + "\n"


def assign_depths():
    """Depth is the descent, so it is derived from position in the run rather
    than hand-typed - that way it can never go backwards between chapters."""
    n = len(LEVELS)
    for i, lv in enumerate(LEVELS):
        lv["depth"] = round(0.05 + 0.95 * i / (n - 1), 3)


def main():
    assign_depths()
    errors = 0
    for i, lv in enumerate(LEVELS):
        errs, warns = analyse(lv)
        tag = f"[{i + 1:2d}] {lv['title']:<20}"
        errors += len(errs)
        for e in errs:
            print(f"{tag} ERROR  {e}")
        for wn in warns:
            print(f"{tag} warn   {wn}")
        if not errs and not warns:
            print(f"{tag} ok")

    print(f"\n{len(LEVELS)} levels, {errors} errors")
    if errors:
        return 1
    if "--check" not in sys.argv:
        path = "app/src/main/java/com/abyss/silt/level/Levels.java"
        with open(path, "w") as f:
            f.write(emit())
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
