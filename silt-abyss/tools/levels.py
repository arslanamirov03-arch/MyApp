#!/usr/bin/env python3
"""
Authoring source for every level in SILT: Abyss.

Levels are written here as ASCII, then validated and emitted as
app/src/main/java/com/abyss/silt/level/Levels.java.

Run:  python3 tools/levels.py            # validate + generate
      python3 tools/levels.py --check    # validate only

The checks are the point of this file. Each level must prove that:
  * it is structurally sane (one spawn, one exit, matching widths),
  * every gate channel has a switch that something in the level can work,
  * the exit is REACHABLE once the right creatures are used, and
  * the exit is NOT reachable if you take away any creature the level relies
    on - which is what catches a barrier that can simply be swum around.

TERRAIN
  .      open water            #  rock
  k      kelp   (BITER cuts)   r  brittle rock (RAMMER shatters)
  ^v<>   current               T  urchin          J  jelly          P  predator
  S      spawn                 X  exit            C  checkpoint     W  whisper
  B      boss anchor           1..7  BITER RAMMER GLOWER SPARK HEAVY PUFFER LEECH

MECHANISMS - the character carries its own channel, so nothing can drift out of
alignment:
  gates    g = ch1   G = ch2   H = ch3
  plates   p = ch1   q = ch2        (HEAVY only)
  nodes    n = ch1   m = ch2        (SPARK only)
  levers   l = ch1   L = ch2   y = ch3   (BITER or RAMMER)

`bars` fills a whole column with one character after the ASCII is laid out, so a
barrier is always full height and can never be swum around by accident.
"""

