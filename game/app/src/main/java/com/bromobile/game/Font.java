    private static final String ORDER =
            "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 .,:!?-+/%()<>*=#'\"_|"
                    + "АБВГДЕЖЗИЙ"
                    + "КЛМНОПРСТУ"
                    + "ФХЦЧШЩЪЫЬЭ"
                    + "ЮЯ";

    private static final HashMap<Character, Integer> INDEX = new HashMap<>();
    private static Bitmap atlas;
    private static final Rect SRC = new Rect(), DST = new Rect();
    private static final Paint P = new Paint();
    private static final HashMap<Integer, PorterDuffColorFilter> FILTERS = new HashMap<>();
    private static int lastColor = 1;

    static {
        for (int i = 0; i < ORDER.length(); i++) INDEX.put(ORDER.charAt(i), i);
        // Lowercase maps onto the uppercase glyph.
        for (char c = 'a'; c <= 'z'; c++) INDEX.put(c, INDEX.get((char) (c - 32)));
        for (char c = 'а'; c <= 'я'; c++) {
            Integer up = INDEX.get((char) (c - 32));
            if (up != null) INDEX.put(c, up);
        }
        INDEX.put('ё', INDEX.get('Е'));  // ё -> Е
        INDEX.put('Ё', INDEX.get('Е'));  // Ё -> Е
        P.setFilterBitmap(false);
        P.setAntiAlias(false);
        P.setDither(false);
        build();
    }

    private static void build() {
        int n = ORDER.length();
        atlas = Bitmap.createBitmap(n * GW, GH, Bitmap.Config.ARGB_8888);
        int[] px = new int[n * GW * GH];
        for (int g = 0; g < n; g++) {
            for (int y = 0; y < GH; y++) {
                String row = G[g * GH + y];
                for (int x = 0; x < GW; x++) {
                    if (row.charAt(x) == '#') px[y * (n * GW) + g * GW + x] = 0xFFFFFFFF;
                }
            }
        }
        atlas.setPixels(px, 0, n * GW, 0, 0, n * GW, GH);
    }

    private Font() { }

    public static int width(String s, int scale) {
        return s.length() * ADV * scale - scale;
    }

    public static int height(int scale) {
        return GH * scale;
    }

    private static void tint(int color) {
        if (color == lastColor) return;
        lastColor = color;
        PorterDuffColorFilter f = FILTERS.get(color);
        if (f == null) {
            f = new PorterDuffColorFilter(color, PorterDuff.Mode.SRC_IN);
            FILTERS.put(color, f);
        }
        P.setColorFilter(f);
    }

    /** Draws {@code s} with its top-left corner at (x, y). */
    public static void draw(Canvas c, String s, int x, int y, int color, int scale) {
        tint(color);
        int cx = x;
        for (int i = 0; i < s.length(); i++) {
            char ch = s.charAt(i);
            Integer gi = INDEX.get(ch);
            if (gi == null) gi = INDEX.get('?');
            if (ch != ' ' && gi != null) {
                SRC.set(gi * GW, 0, gi * GW + GW, GH);
                DST.set(cx, y, cx + GW * scale, y + GH * scale);
                c.drawBitmap(atlas, SRC, DST, P);
            }
            cx += ADV * scale;
        }
    }

    /** Draws with a 1px (scaled) drop shadow for readability over busy scenes. */
    public static void shadow(Canvas c, String s, int x, int y, int color, int scale) {
        draw(c, s, x + scale, y + scale, 0xFF0B0910, scale);
        draw(c, s, x, y, color, scale);
    }

    /** Draws horizontally centred on {@code cxPos}. */
    public static void center(Canvas c, String s, int cxPos, int y, int color, int scale) {
        shadow(c, s, cxPos - width(s, scale) / 2, y, color, scale);
    }

    /** Draws with a full 1px outline — used for titles and boss names. */
    public static void outline(Canvas c, String s, int x, int y, int color, int outline, int scale) {
        draw(c, s, x - scale, y, outline, scale);
        draw(c, s, x + scale, y, outline, scale);
        draw(c, s, x, y - scale, outline, scale);
        draw(c, s, x, y + scale, outline, scale);
        draw(c, s, x, y, color, scale);
    }

    public static void outlineCenter(Canvas c, String s, int cxPos, int y, int color, int ol, int scale) {
        outline(c, s, cxPos - width(s, scale) / 2, y, color, ol, scale);
    }
